"""Replay a benchmark completion through the real parser and fixture runtime.

The input text is generated by the benchmark's real model. This module performs
no inference; its deliberately labelled replay manager returns exactly that
text. All execution uses separate in-memory databases and fictional fixtures.
"""

from __future__ import annotations

from copy import deepcopy
import hashlib
import json
from typing import Any

from splice.gateway import Gateway
from splice.local_intent import LocalOnDeviceIntentAdapter
from splice.runtime import Runtime


_GRANTS = {"food:read", "food_order_draft:write", "finance:read", "finance_budget:read"}


class _CompletionReplay:
    def __init__(self, text: str) -> None:
        self.text = text

    def generate(self, messages, *, offline=False):
        return {
            "text": self.text,
            "model": "benchmark-completion-replay-no-new-inference",
            "inference_source": "replay_of_this_benchmark_completion",
            "new_model_inference": False,
            "offline": bool(offline),
        }


def _error(exc: Exception) -> dict[str, str]:
    return {"type": type(exc).__name__, "message": str(exc)}


def _runtime_case(name: str, intent: dict, registry) -> dict[str, Any]:
    grants = set(_GRANTS)
    if name == "missing_finance_permission":
        grants -= {"finance:read", "finance_budget:read"}
    gateway = None
    runtime = None
    case: dict[str, Any] = {
        "status": "failed",
        "error": None,
        "draft_count": 0,
        "facts": deepcopy(intent["facts"]),
        "gates": deepcopy(intent["gates"]),
        "outputs": {},
        "grants": sorted(grants),
        "fixture_changes": [],
        "confirmed_fixture_draft_only": True,
    }
    try:
        gateway = Gateway(grants, db_path=":memory:")
        if name == "insufficient_cash":
            accounts = gateway.resources["cash_accounts"]
            if not accounts:
                raise ValueError("cash_accounts fixture must contain at least one account")
            for row in accounts:
                if "balance_cny" not in row:
                    raise ValueError("cash account fixture lacks balance_cny")
                row["balance_cny"] = 0
            case["fixture_changes"].append({
                "resource": "cash_accounts", "field": "balance_cny",
                "value": 0, "rows_changed": len(accounts),
            })
        runtime = Runtime(registry, gateway)
        report = runtime.run(deepcopy(intent), confirmed=True)
        case.update({
            "status": report["status"],
            "error": report.get("error"),
            "outputs": report["outputs"],
            "draft_count": gateway.draft_count(),
            "plan": report["plan"],
            "gate_checks": [item for item in report["trace"] if item.get("event") == "gate"],
            "trace": report["trace"],
            "audit": report["audit"],
        })
        # Expose computed facts as evidence too. Rolled-back effect outputs are
        # excluded, matching Runtime's treatment of committed request outputs.
        manifests = {manifest["id"]: manifest for manifest in registry.all()}
        for event in report["trace"]:
            if event.get("event") != "output":
                continue
            manifest = manifests[event["plugin"]]
            if manifest["effects"] and report["status"] != "completed":
                continue
            for field, value in event["output"].items():
                fact = manifest["output_schema"]["properties"][field]["x-fact"]
                case["facts"][fact] = deepcopy(value)
    except Exception as exc:
        # Unexpected faults remain explicitly distinguishable from a deliberate
        # Runtime "blocked" decision; no exception is converted to success.
        case.update(status="failed", error=_error(exc))
        if runtime is not None:
            case["trace"] = deepcopy(runtime.trace)
        if gateway is not None:
            case["audit"] = deepcopy(gateway.audit)
            case["draft_count"] = gateway.draft_count()
    finally:
        if gateway is not None:
            gateway.close()
    return case


def recheck_completion(text: str, utterance: str, registry, learning) -> dict[str, Any]:
    """Validate the exact completion and rerun its unchanged intent in 3 cases.

    ``registry`` and ``learning`` are the already-loaded Registry/LearningStore
    objects used by the real benchmark. Model generation is not repeated. Parser
    format normalization is the existing production behavior and is recorded.
    ``status``/``outputs``/``draft_count`` at the top level describe default
    fixtures; ``cases`` includes the two permission/cash counterfactuals.
    """
    result: dict[str, Any] = {
        "inference_source": "replay_of_this_benchmark_completion",
        "new_model_inference": False,
        "completion_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "status": "failed",
        "parse_status": "failed",
        "error": None,
        "facts": {},
        "gates": [],
        "requested_outputs": [],
        "outputs": {},
        "draft_count": 0,
        "format_corrections": [],
        "cases": {},
        "execution_scope": "fictional_fixtures_separate_in_memory_databases",
    }
    adapter = LocalOnDeviceIntentAdapter(registry, learning, _CompletionReplay(text))
    try:
        intent = adapter.parse(utterance)
        result.update(
            parse_status="parsed",
            facts=deepcopy(intent["facts"]),
            gates=deepcopy(intent["gates"]),
            requested_outputs=deepcopy(intent["requested_outputs"]),
            format_corrections=deepcopy(adapter.last_report.get("format_corrections", [])),
        )
    except Exception as exc:
        parse_report = deepcopy(getattr(exc, "report", adapter.last_report))
        result.update(
            error=_error(exc),
            parse_report=parse_report,
            format_corrections=deepcopy(parse_report.get("format_corrections", [])),
        )
        predicted = parse_report.get("model_intent", {})
        if isinstance(predicted, dict):
            for key in ("facts", "gates", "requested_outputs"):
                if key in predicted:
                    result[key] = deepcopy(predicted[key])
        result["execution_skipped"] = "parser_rejected_completion"
        # Failures include the original parser report and are returned as data
        # so one malformed completion cannot erase other benchmark evidence.
        json.dumps(result, ensure_ascii=False, allow_nan=False)
        return result
    for name in ("default", "insufficient_cash", "missing_finance_permission"):
        result["cases"][name] = _runtime_case(name, intent, registry)
    default = result["cases"]["default"]
    for key in ("status", "error", "outputs", "draft_count"):
        result[key] = deepcopy(default[key])
    json.dumps(result, ensure_ascii=False, allow_nan=False)
    return result
